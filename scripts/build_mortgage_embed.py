"""Builds site-snippet/mortgage-calculator-embed.html (the Lofty paste-in) from the web app,
so the page and the app always show the same calculators.

Run after changing web/mortgage-calculator/index.html or apps/mortgage-calculator/src/mortgage.js:
    python3 scripts/build_mortgage_embed.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
page = (ROOT / 'web/mortgage-calculator/index.html').read_text()
math = (ROOT / 'apps/mortgage-calculator/src/mortgage.js').read_text()

main = re.search(r'<main>\n(.*?)</main>', page, re.S).group(1)
nav = re.search(r'<nav>(.*?)</nav>', page, re.S).group(1)
script = re.search(r'<script type="module">\n(.*?)</script>', page, re.S).group(1)
script = '\n'.join(l for l in script.splitlines() if not l.startswith(('import ', "if ('serviceWorker'")))

# Every id and class gets an mc- prefix so the page's own CSS (e.g. a Bootstrap .row) can't touch it.
CLASSES = ['inline', 'chips', 'on', 'row', 'total', 'note', 'warn']
def prefix(s):
    s = re.sub(r'id="', 'id="mc-', s)
    s = re.sub(r'class="([^"$]*)"', lambda m: 'class="%s"' % ' '.join('mc-' + c for c in m.group(1).split()), s)
    return s
main, nav = prefix(main), prefix(nav)
# The Lofty page has its own h1, so headings drop one level.
main = main.replace('h2>', 'h3>').replace('h1>', 'h2>')
for c in CLASSES:
    script = script.replace(f"'.{c}'", f"'.mc-{c}'").replace(f"('{c}'", f"('mc-{c}'")
script = (script
    .replace('class="row${total ? \' total\' : \'\'}"', 'class="mc-row${total ? \' mc-total\' : \'\'}"')
    .replace('class="note"', 'class="mc-note"').replace('class="warn"', 'class="mc-warn"')
    .replace("' class=\"on\"'", "' class=\"mc-on\"'")
    .replace("document.getElementById(id)", "document.getElementById('mc-' + id)")
    .replace("document.querySelector('nav')", "$('tabs')")
    .replace("document.querySelectorAll('nav button')", "$('tabs').querySelectorAll('button')")
    .replace('  scrollTo(0, 0);\n', ''))
math = math.replace('export ', '')

out = f'''<!-- Mortgage Calculator: paste into an HTML block on the Lofty page home-nader.com/mortgage-calculators.
     Self-contained, no external files. Generated by scripts/build_mortgage_embed.py from web/mortgage-calculator;
     edit those and re-run the script rather than editing this file.
     Everything is scoped to #mc-app. It inherits your page's font and text colour; to match your brand,
     set the accent variable below (or override it from your page CSS), e.g. #mc-app{{--mc-accent:#c8102e}}. -->
<style>
  #mc-app{{--mc-accent:#0f4c81;--mc-border:rgba(128,128,128,.3);--mc-card:rgba(128,128,128,.12);--mc-muted:rgba(128,128,128,.95);--mc-warn:#b91c1c;
    max-width:560px;margin:0 auto;padding:16px;font-family:inherit;font-size:16px;line-height:1.4;color:inherit;box-sizing:border-box}}
  #mc-app *{{box-sizing:border-box;font-family:inherit}}
  #mc-app h2{{font-size:22px;margin:0 0 16px;color:inherit}}
  #mc-app h3{{font-size:17px;margin:24px 0 4px;color:inherit}}
  #mc-app label{{display:block;color:var(--mc-muted);margin:0 0 6px;font-weight:normal}}
  #mc-app input[type=text]{{width:100%;height:auto;font-size:18px;padding:12px;margin:0 0 16px;border:1px solid var(--mc-border);border-radius:8px;background:transparent;color:inherit}}
  #mc-app .mc-inline{{display:flex;gap:8px}}
  #mc-app .mc-inline input{{flex:1}}
  #mc-app .mc-chips{{display:flex;flex-wrap:wrap;gap:8px;margin:0 0 16px}}
  #mc-app .mc-inline .mc-chips{{margin:0;flex-wrap:nowrap;align-self:flex-start}}
  #mc-app .mc-chips button{{border:1px solid var(--mc-border);border-radius:8px;padding:10px 14px;background:none;color:inherit;font-size:14px;cursor:pointer;line-height:1.2}}
  #mc-app .mc-chips button.mc-on{{background:var(--mc-accent);border-color:var(--mc-accent);color:#fff;font-weight:700}}
  #mc-app .mc-row{{display:flex;justify-content:space-between;align-items:center;gap:12px;margin:0;padding:10px 0;border-bottom:1px solid var(--mc-border)}}
  #mc-app .mc-total{{background:var(--mc-card);padding:10px;border-radius:8px;margin-top:8px;border:0;color:var(--mc-accent);font-weight:700;font-size:18px}}
  #mc-app .mc-note{{color:var(--mc-muted);font-size:12px;margin:8px 0}}
  #mc-app .mc-warn{{color:var(--mc-warn);font-size:14px}}
  #mc-app .mc-tabs{{display:flex;border-bottom:1px solid var(--mc-border);margin-bottom:16px}}
  #mc-app .mc-tabs button{{flex:1;padding:12px;border:0;background:none;color:var(--mc-muted);font-size:14px;cursor:pointer}}
  #mc-app .mc-tabs button.mc-on{{color:var(--mc-accent);font-weight:700;border-bottom:2px solid var(--mc-accent)}}
  #mc-app [hidden]{{display:none}}
</style>
<div id="mc-app">
  <div class="mc-tabs" id="mc-tabs">{nav}</div>
{main}</div>
<script>
(function () {{
{math}
{script}}})();
</script>
'''
(ROOT / 'site-snippet/mortgage-calculator-embed.html').write_text(out)
print('wrote site-snippet/mortgage-calculator-embed.html')
